/*
 * The CycloneDX view of the only native code either shipped artifact carries:
 * the QPDF WebAssembly runtime under `vendor/qpdf-wasm/runtime/`.
 *
 * `SBOM.cdx.json` is otherwise generated from `package-lock.json`, so it
 * described npm dependencies and nothing else. The runtime is compiled from
 * pinned C/C++ source by a pinned Emscripten toolchain, and none of that had a
 * component. The notices shipped and `SHARE-PROVENANCE.json` hashed every
 * file, so this was never a licence-compliance failure — but a bill of
 * materials that omits the only native code in the bundle misleads whoever
 * consumes it.
 *
 * Everything below is DERIVED from `vendor/qpdf-wasm/runtime.provenance.json`,
 * which is itself generated by `scripts/vendor-qpdf-wasm-runtime.mjs` from a
 * build that already reproduced `expected-output.json`. Nothing here restates
 * a version, a digest or a licence that is written down somewhere else: a
 * component list maintained by hand would drift from the lock the first time
 * anyone bumped a source, which is exactly the failure this repository keeps
 * paying for. `test/sbom-native-components.test.js` re-derives the same set
 * independently from `vendor/qpdf-wasm/sources.lock.json` and the shipped
 * notice manifest, so the two sides cannot be wrong together.
 *
 * What counts as a component, and why:
 *
 *   - qpdf, zlib and libjpeg-turbo are compiled from the pinned source
 *     archives in `sources.lock.json` and linked into `qpdf.wasm`. Their code
 *     is redistributed, so they are components, each hashed against the source
 *     archive digest that was actually fetched.
 *
 *   - musl, compiler-rt, libc++, libc++abi, libunwind and Emscripten's own
 *     generated runtime are supplied by the toolchain, but they are not
 *     tooling: they are statically linked into `qpdf.wasm` (and, for the
 *     generated runtime, emitted into `qpdf.mjs`) and redistributed with it.
 *     That is why their notices ship. Omitting them would understate the bill
 *     by leaving out shipped code, so they are components too. They have no
 *     separately isolable source archive in this build, so rather than invent
 *     a digest for a subcomponent that cannot be isolated, each is hashed
 *     against the pinned `emscripten/emsdk` image digest that produced it and
 *     says so in `pdf-tools:qpdf-wasm-hash-subject`.
 *
 *   - The Emscripten compiler itself — emcc, clang, Binaryen, the emsdk image
 *     as a program — is build tooling whose code is NOT redistributed. Listing
 *     a compiler among shipped components would overstate the bill just as
 *     badly as omitting linked code understates it, so the image is recorded
 *     as `metadata.tools.components` instead: present as provenance, absent
 *     from the shipped inventory.
 */

import { QPDF_WASM_RUNTIME_PROVENANCE } from "./qpdf-wasm-runtime.mjs";

const RUNTIME_DIRECTORY = "vendor/qpdf-wasm/runtime";
const RUNTIME_BOM_REF = "urn:pdf-tools:qpdf-wasm-runtime";
const SOURCE_BOM_REF_PREFIX = "urn:pdf-tools:qpdf-wasm-source";
const TOOLCHAIN_BOM_REF_PREFIX = "urn:pdf-tools:qpdf-wasm-toolchain-runtime";
export const QPDF_WASM_BUILD_TOOLCHAIN_BOM_REF = "urn:pdf-tools:qpdf-wasm-build-toolchain";
export const QPDF_WASM_RUNTIME_COMPONENT_BOM_REF = RUNTIME_BOM_REF;

/** `Emscripten <version> generated runtime` — the emitted JS/wasm glue. */
const GENERATED_RUNTIME_NOTICE = /^Emscripten (?<version>\S+) generated runtime$/;
/** `<library> bundled by Emscripten <version>` — a linked toolchain library. */
const TOOLCHAIN_LIBRARY_NOTICE = /^(?<name>.+?) bundled by Emscripten (?<version>\S+)$/;
/** `<name> <version> bundled-code notices` — a supplementary notice, not a component. */
const SUPPLEMENTARY_NOTICE = /^(?<name>.+?) (?<version>\d\S*) bundled-code notices$/;
/** `<name> <version>` — the primary notice for a pinned source archive. */
const SOURCE_NOTICE = /^(?<name>.+?) (?<version>\d\S*)$/;

function compareCodePoints(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function purlSegment(value) {
  return value.split("/").map(part => encodeURIComponent(part)).join("/");
}

function purlQualifiers(entries) {
  const pairs = entries
    .filter(([, value]) => value !== undefined && value !== null && value !== "")
    .map(([key, value]) => `${key}=${encodeURIComponent(value)}`);
  return pairs.length > 0 ? `?${pairs.join("&")}` : "";
}

function property(name, value) {
  return { name: `pdf-tools:${name}`, value };
}

/**
 * Classifies every notice the runtime ships. Throws on anything unrecognised
 * rather than skipping it, so a new bundled licence cannot slip through as an
 * unlisted component.
 */
function classifyNotices(provenance) {
  const sourceKeys = new Set(
    provenance.build.sources.map(source => `${source.name} ${source.version}`),
  );
  const primaryBySourceKey = new Map();
  const supplementaryBySourceKey = new Map();
  const toolchainNotices = [];
  for (const notice of provenance.notices.components) {
    const supplementary = SUPPLEMENTARY_NOTICE.exec(notice.component);
    if (supplementary) {
      const key = `${supplementary.groups.name} ${supplementary.groups.version}`;
      if (!sourceKeys.has(key)) {
        throw new Error(`QPDF WASM notice describes an unpinned source: ${notice.component}`);
      }
      const existing = supplementaryBySourceKey.get(key) || [];
      supplementaryBySourceKey.set(key, [...existing, notice]);
      continue;
    }
    const generated = GENERATED_RUNTIME_NOTICE.exec(notice.component);
    if (generated) {
      toolchainNotices.push({
        name: "emscripten-generated-runtime",
        version: generated.groups.version,
        linkage: `emitted into ${RUNTIME_DIRECTORY}/qpdf.mjs and ${RUNTIME_DIRECTORY}/qpdf.wasm`,
        notice,
      });
      continue;
    }
    const toolchain = TOOLCHAIN_LIBRARY_NOTICE.exec(notice.component);
    if (toolchain) {
      toolchainNotices.push({
        name: toolchain.groups.name,
        version: toolchain.groups.version,
        linkage: `statically linked into ${RUNTIME_DIRECTORY}/qpdf.wasm`,
        notice,
      });
      continue;
    }
    const source = SOURCE_NOTICE.exec(notice.component);
    const key = source ? `${source.groups.name} ${source.groups.version}` : null;
    if (!key || !sourceKeys.has(key)) {
      throw new Error(`QPDF WASM notice is not classifiable as a component or a notice: ${notice.component}`);
    }
    if (primaryBySourceKey.has(key)) {
      throw new Error(`QPDF WASM source has more than one primary notice: ${notice.component}`);
    }
    primaryBySourceKey.set(key, notice);
  }
  for (const key of sourceKeys) {
    if (!primaryBySourceKey.has(key)) {
      throw new Error(`QPDF WASM source ships no licence notice: ${key}`);
    }
  }
  return { primaryBySourceKey, supplementaryBySourceKey, toolchainNotices };
}

function noticeReference(provenance, notice) {
  const assetPath = `${RUNTIME_DIRECTORY}/${notice.file}`;
  const asset = provenance.runtime_assets.files.find(file => file.path === assetPath);
  if (!asset) {
    throw new Error(`QPDF WASM notice ${notice.file} is not a shipped runtime asset`);
  }
  if (asset.sha256 !== notice.sha256) {
    throw new Error(
      `QPDF WASM notice ${notice.file} digest disagrees with the shipped asset: `
      + `${notice.sha256} != ${asset.sha256}`,
    );
  }
  return {
    type: "license",
    url: assetPath,
    comment: `${notice.component} (${notice.spdx})`,
    hashes: [{ alg: "SHA-256", content: asset.sha256 }],
  };
}

function runtimeAsset(provenance, relativePath) {
  const assetPath = `${RUNTIME_DIRECTORY}/${relativePath}`;
  const asset = provenance.runtime_assets.files.find(file => file.path === assetPath);
  if (!asset) throw new Error(`QPDF WASM runtime asset is not shipped: ${assetPath}`);
  return asset;
}

function runtimeArtifactVersion(provenance) {
  const suffix = provenance.artifact_id.split(".").at(-1);
  if (!/^v\d+$/.test(suffix)) {
    throw new Error(`QPDF WASM artifact id carries no version suffix: ${provenance.artifact_id}`);
  }
  return suffix;
}

/**
 * The composite licence of a statically linked artifact is the conjunction of
 * every licence linked into it: a redistributor has to satisfy all of them.
 * Derived from the shipped notice manifest, with any compound term
 * parenthesised so the result stays a well-formed SPDX expression.
 */
function compositeLicenseExpression(provenance) {
  const expressions = [...new Set(provenance.notices.components.map(notice => notice.spdx))]
    .sort(compareCodePoints)
    .map(expression => (/\s/.test(expression) ? `(${expression})` : expression));
  if (expressions.length === 0) throw new Error("QPDF WASM runtime ships no licence notices");
  return expressions.join(" AND ");
}

function runtimeComponent(provenance) {
  const binary = runtimeAsset(provenance, "qpdf.wasm");
  const loader = runtimeAsset(provenance, "qpdf.mjs");
  const buildInputs = runtimeAsset(provenance, "BUILD-INPUTS.json");
  const versions = runtimeAsset(provenance, "THIRD_PARTY_VERSIONS.txt");
  const noticeManifest = runtimeAsset(provenance, "licenses/manifest.json");
  const version = runtimeArtifactVersion(provenance);
  return {
    type: "library",
    "bom-ref": RUNTIME_BOM_REF,
    group: "pdf-tools",
    name: "qpdf-wasm-runtime",
    version,
    scope: "required",
    description:
      "Reproducible Emscripten build of QPDF and its linked native libraries, shipped as WebAssembly at "
      + `${RUNTIME_DIRECTORY}/ in both the MCPB and the share ZIP.`,
    purl: `pkg:generic/pdf-tools/qpdf-wasm-runtime@${version}`
      + purlQualifiers([["checksum", `sha256:${binary.sha256}`], ["download_url", binary.path]]),
    hashes: [{ alg: "SHA-256", content: binary.sha256 }],
    licenses: [{ expression: compositeLicenseExpression(provenance) }],
    externalReferences: [
      {
        type: "distribution",
        url: binary.path,
        comment: "Compiled WebAssembly module as shipped",
        hashes: [{ alg: "SHA-256", content: binary.sha256 }],
      },
      {
        type: "distribution",
        url: loader.path,
        comment: "Emscripten loader module as shipped",
        hashes: [{ alg: "SHA-256", content: loader.sha256 }],
      },
      {
        type: "build-meta",
        url: buildInputs.path,
        comment: "Pinned build inputs that travel with the runtime",
        hashes: [{ alg: "SHA-256", content: buildInputs.sha256 }],
      },
      {
        type: "build-meta",
        url: versions.path,
        comment: "Third-party version summary that travels with the runtime",
        hashes: [{ alg: "SHA-256", content: versions.sha256 }],
      },
      {
        type: "license",
        url: noticeManifest.path,
        comment: "Notice manifest covering every bundled licence",
        hashes: [{ alg: "SHA-256", content: noticeManifest.sha256 }],
      },
    ],
    properties: [
      property("qpdf-wasm-artifact-id", provenance.artifact_id),
      property("qpdf-wasm-hash-subject", binary.path),
      property("qpdf-wasm-source-date-epoch", String(provenance.build.source_date_epoch)),
      property("qpdf-wasm-build-toolchain", `${provenance.build.toolchain.image}:`
        + `${provenance.build.toolchain.version} ${provenance.build.toolchain.platform}`
        + `@${provenance.build.toolchain.digest}`),
      property("qpdf-wasm-reproducibility-gate", provenance.reproduction.release_gate.command),
      property(
        "qpdf-wasm-licence-basis",
        "Conjunction of every notice the runtime ships, because all of them are linked into one "
        + "artifact; each individual licence is attached to the component it actually covers.",
      ),
    ],
  };
}

function sourceComponents(provenance, { primaryBySourceKey, supplementaryBySourceKey }) {
  return provenance.build.sources.map(source => {
    const key = `${source.name} ${source.version}`;
    const primary = primaryBySourceKey.get(key);
    return {
      type: "library",
      "bom-ref": `${SOURCE_BOM_REF_PREFIX}:${source.name}@${source.version}`,
      name: source.name,
      version: source.version,
      scope: "required",
      description: `Compiled from ${source.filename} and linked into ${RUNTIME_DIRECTORY}/qpdf.wasm.`,
      purl: `pkg:generic/${purlSegment(source.name)}@${encodeURIComponent(source.version)}`
        + purlQualifiers([["checksum", `sha256:${source.sha256}`], ["download_url", source.url]]),
      hashes: [{ alg: "SHA-256", content: source.sha256 }],
      licenses: [{ expression: primary.spdx }],
      externalReferences: [
        {
          type: "source-distribution",
          url: source.url,
          comment: "Pinned upstream source archive this component was built from",
          hashes: [{ alg: "SHA-256", content: source.sha256 }],
        },
        noticeReference(provenance, primary),
        ...(supplementaryBySourceKey.get(key) || [])
          .map(notice => noticeReference(provenance, notice)),
      ],
      properties: [
        property("qpdf-wasm-hash-subject", source.filename),
        property("qpdf-wasm-linkage", `statically linked into ${RUNTIME_DIRECTORY}/qpdf.wasm`),
        property("qpdf-wasm-source-archive", source.filename),
      ],
    };
  });
}

function toolchainComponents(provenance, toolchainNotices) {
  const { image, version: toolchainVersion, platform, digest, upstream } = provenance.build.toolchain;
  return toolchainNotices.map(entry => ({
    type: "library",
    "bom-ref": `${TOOLCHAIN_BOM_REF_PREFIX}:${entry.name}@${entry.version}`,
    group: "emscripten",
    name: entry.name,
    version: entry.version,
    scope: "required",
    description: `${entry.notice.component}; ${entry.linkage}.`,
    purl: `pkg:generic/emscripten/${purlSegment(entry.name)}@${encodeURIComponent(entry.version)}`
      + purlQualifiers([["checksum", digest], ["distro", `${image}:${toolchainVersion}`]]),
    hashes: [{ alg: "SHA-256", content: digest.replace(/^sha256:/, "") }],
    licenses: [{ expression: entry.notice.spdx }],
    externalReferences: [
      {
        type: "build-system",
        url: upstream,
        comment: `Supplied by the pinned ${image}:${toolchainVersion} ${platform} build image`,
        hashes: [{ alg: "SHA-256", content: digest.replace(/^sha256:/, "") }],
      },
      noticeReference(provenance, entry.notice),
    ],
    properties: [
      property("qpdf-wasm-linkage", entry.linkage),
      property("qpdf-wasm-provider", `${image}:${toolchainVersion} ${platform}@${digest}`),
      property("qpdf-wasm-hash-subject",
        `${image}:${toolchainVersion} ${platform} image digest; this library has no separately `
        + "isolable source archive in this build, so the pinned image that produced it is hashed "
        + "instead of inventing a digest for something that cannot be isolated"),
      property("qpdf-wasm-version-basis",
        `Emscripten release version; the upstream ${entry.name} version is not independently pinned by this build`),
    ],
  }));
}

/**
 * The build image, recorded as tooling rather than as a shipped component.
 * The compiler produced the artifact; it is not inside it.
 */
export function deriveQpdfWasmToolComponent(provenance = QPDF_WASM_RUNTIME_PROVENANCE) {
  const { image, version, platform, digest, upstream, name } = provenance.build.toolchain;
  const [group, imageName] = image.includes("/") ? image.split("/") : [undefined, image];
  return {
    type: "container",
    "bom-ref": QPDF_WASM_BUILD_TOOLCHAIN_BOM_REF,
    ...(group ? { group } : {}),
    name: imageName,
    version,
    description:
      `${name} ${version}, the pinned build image that compiled ${RUNTIME_DIRECTORY}/. Build tooling only: `
      + "the compiler is not redistributed, while the runtime libraries it statically links are listed as "
      + "components.",
    purl: `pkg:docker/${purlSegment(image)}@${digest}${purlQualifiers([["platform", platform]])}`,
    hashes: [{ alg: "SHA-256", content: digest.replace(/^sha256:/, "") }],
    externalReferences: [{ type: "build-system", url: upstream }],
    properties: [
      property("qpdf-wasm-toolchain-role", "build-only; not redistributed in any shipped artifact"),
      property("qpdf-wasm-toolchain-platform", platform),
    ],
  };
}

/**
 * Every CycloneDX component the QPDF WebAssembly runtime contributes, sorted
 * by `bom-ref` so the generated SBOM is byte-stable.
 */
export function deriveQpdfWasmSbomComponents(provenance = QPDF_WASM_RUNTIME_PROVENANCE) {
  const classified = classifyNotices(provenance);
  const components = [
    runtimeComponent(provenance),
    ...sourceComponents(provenance, classified),
    ...toolchainComponents(provenance, classified.toolchainNotices),
  ].sort((left, right) => compareCodePoints(left["bom-ref"], right["bom-ref"]));
  const refs = new Set(components.map(component => component["bom-ref"]));
  if (refs.size !== components.length) {
    throw new Error("QPDF WASM SBOM components contain a duplicate bom-ref");
  }
  return components;
}

/**
 * Dependency edges for the native components. The runtime is the artifact that
 * ships, and everything compiled or linked into it hangs off it rather than
 * floating free next to the npm graph.
 */
export function deriveQpdfWasmSbomDependencies(components) {
  const childRefs = components
    .map(component => component["bom-ref"])
    .filter(ref => ref !== RUNTIME_BOM_REF)
    .sort(compareCodePoints);
  return [
    { ref: RUNTIME_BOM_REF, dependsOn: childRefs },
    ...childRefs.map(ref => ({ ref, dependsOn: [] })),
  ];
}

export const QPDF_WASM_SBOM_COMPONENTS = Object.freeze(deriveQpdfWasmSbomComponents());
export const QPDF_WASM_SBOM_DEPENDENCIES = Object.freeze(
  deriveQpdfWasmSbomDependencies(QPDF_WASM_SBOM_COMPONENTS),
);
export const QPDF_WASM_BUILD_TOOL_COMPONENT = Object.freeze(deriveQpdfWasmToolComponent());
